"""
Страница обучения - руководство по использованию платформы
"""
import streamlit as st


def show_tutorial_page():
    """Страница с обучающим материалом"""

    st.title("📚 Обучение")
    st.markdown("Пошаговое руководство по работе с платформой TwoSigma")

    st.divider()

    # Введение
    st.markdown("""
    ## 👋 Добро пожаловать!

    Это руководство поможет вам быстро освоить платформу и провести ваш первый A/B тест.
    Мы пройдем весь путь от загрузки данных до получения результатов эксперимента.
    """)

    st.divider()

    # Шаг 1: Загрузка датасета
    with st.expander("📁 Шаг 1: Загрузка датасета", expanded=True):
        st.markdown("""
        ### Что нужно сделать:
        1. Перейдите в раздел **"Датасеты"** через боковое меню
        2. Нажмите кнопку **"➕ Загрузить датасет"**
        3. Выберите CSV-файл с вашими данными
        4. Укажите название датасета

        ### Требования к датасету:
        - Формат: **CSV** (разделитель - запятая)
        - Обязательные колонки:
          - **user_id** - уникальный идентификатор пользователя
          - **date** - дата события (формат: YYYY-MM-DD)
          - Колонки с метриками (например: revenue, order_id, status)

        ### Пример структуры данных:
        ```csv
        user_id,order_date,revenue,order_id,status
        U001,2025-03-01,234.50,O1001,completed
        U002,2025-03-01,189.90,O1002,completed
        U003,2025-03-02,0.00,O1003,cancelled
        ```

        💡 **Совет:** Убедитесь, что данные покрывают период, в котором вы планируете проводить эксперимент.
        """)

    # Шаг 2: Создание метрики
    with st.expander("📊 Шаг 2: Создание метрики"):
        st.markdown("""
        ### Что нужно сделать:
        1. Перейдите в раздел **"Метрики"**
        2. Нажмите **"➕ Добавить новую метрику"**
        3. Выберите способ создания:
           - **🔧 Визуальный конструктор** - для готовых шаблонов метрик
           - **💻 SQL-запрос** - для кастомных расчетов

        ⚠️ **Важно для A/B тестов:** Для корректной работы экспериментов используйте **визуальный конструктор**.
        SQL-метрики предназначены для аналитических запросов и не поддерживают автоматическое разбиение по группам эксперимента.

        ### Популярные типы метрик:

        **💰 Revenue (Выручка)**
        - Общая сумма выручки за период
        - Поле: колонка с суммой заказа

        **📦 AOV (Average Order Value)**
        - Средний чек
        - Поля: revenue (выручка) + order_id (идентификатор заказа)

        **👤 ARPU (Average Revenue Per User)**
        - Средняя выручка на пользователя
        - Поле: revenue (выручка)

        **✅ Conversion Rate (Конверсия)**
        - Процент успешных действий
        - Поля: status (статус) + значение успеха (например, "completed")

        ### Предпросмотр метрики:
        После настройки полей нажмите **"🔍 Предпросмотр метрики"**, чтобы увидеть:
        - График динамики по периодам
        - Среднее и суммарное значение
        - Детальную таблицу

        💡 **Совет:** Создайте несколько метрик для комплексной оценки эксперимента.
        """)

    # Шаг 3: Создание эксперимента
    with st.expander("🧪 Шаг 3: Создание эксперимента"):
        st.markdown("""
        ### Что нужно сделать:
        1. Перейдите в раздел **"Эксперименты"**
        2. Нажмите **"➕ Создать эксперимент"**
        3. Заполните параметры эксперимента:

        ### Основные параметры:

        **Название эксперимента**
        - Краткое описание того, что тестируете
        - Пример: "Новый дизайн кнопки оформления заказа"

        **Датасет**
        - Выберите загруженный ранее датасет

        **Метрика**
        - Выберите метрику, которую будете отслеживать
        - Это основной показатель успеха эксперимента

        **Период эксперимента**
        - Дата начала и окончания
        - Рекомендуется минимум 1-2 недели для статистической значимости

        **Настройка групп**
        - Количество групп (обычно 2: контроль и тест)
        - Соотношение (например, 50/50)
        - Seed для воспроизводимости (можно оставить по умолчанию)

        **Тип статистического теста**
        - **t-test** - для непрерывных метрик (revenue, AOV, ARPU)
        - **z-test** - для конверсий и пропорций

        ### После создания:
        Система автоматически:
        - Разделит пользователей на группы
        - Создаст специальный датасет эксперимента
        - Сохранит конфигурацию

        💡 **Совет:** Используйте seed для детерминированного разбиения - один и тот же пользователь всегда попадет в одну группу.
        """)

    # Шаг 4: Проведение эксперимента
    with st.expander("⏳ Шаг 4: Проведение эксперимента"):
        st.markdown("""
        ### Что происходит:

        После создания эксперимента начинается период сбора данных:

        1. **Пользователи разделены на группы**
           - Контрольная группа (control) - видит текущую версию
           - Тестовая группа (test) - видит новую версию

        2. **Сбор данных**
           - В течение периода эксперимента собираются данные о поведении пользователей
           - Каждое действие пользователя записывается в датасет

        3. **Мониторинг (опционально)**
           - Можете нажать **"📊 Рассчитать результаты"** для просмотра промежуточных данных
           - Если данные неполные, увидите предупреждение и графики текущего состояния

        ### Важно:
        - ⏰ Дождитесь окончания периода эксперимента
        - 📊 Не принимайте решения на основе промежуточных результатов
        - 📈 Убедитесь, что размер выборки достаточный (минимум 30 наблюдений на группу)

        💡 **Совет:** Чем дольше эксперимент, тем надежнее результаты. Рекомендуется минимум 1-2 недели.
        """)

    # Шаг 5: Обновление датасета
    with st.expander("🔄 Шаг 5: Обновление датасета с новыми данными"):
        st.markdown("""
        ### Когда эксперимент завершен:

        1. **Соберите финальные данные**
           - Убедитесь, что данные покрывают весь период эксперимента
           - Включая дату окончания

        2. **Обновите датасет**
           - Перейдите в раздел **"Датасеты"**
           - Найдите ваш датасет
           - Нажмите **"🔄 Обновить"** или загрузите новый файл с тем же названием

        3. **Проверьте данные**
           - Убедитесь, что новые данные загружены
           - Проверьте количество строк и период

        ### Формат обновленных данных:
        - Та же структура CSV, что и при первой загрузке
        - Те же названия колонок
        - Данные должны включать весь период эксперимента

        💡 **Совет:** Можете загрузить полный датасет (старые + новые данные) или только новые записи.
        """)

    # Шаг 6: Расчет результатов
    with st.expander("📈 Шаг 6: Расчет и анализ результатов"):
        st.markdown("""
        ### Финальный расчет:

        1. **Перейдите в раздел "Эксперименты"**
        2. Найдите ваш эксперимент
        3. Нажмите **"📊 Рассчитать результаты"**

        ### Что вы увидите:

        **📊 Таблица сравнения групп**
        - Размер выборки каждой группы
        - Значение метрики
        - Стандартное отклонение
        - Разница с контрольной группой (%)
        - p-value (уровень значимости)
        - Статистическая значимость (✅/❌)

        **📊 Столбчатая диаграмма**
        - Визуальное сравнение групп
        - Цветовая индикация:
          - 🔵 Синий - контрольная группа
          - 🟢 Зеленый - значимое улучшение
          - 🔴 Красный - значимое ухудшение
          - 🟠 Оранжевый - незначимое изменение

        **📈 График динамики**
        - Изменение метрики по времени для каждой группы
        - Помогает увидеть тренды и аномалии

        **📐 Статистическая сводка**
        - Интерпретация результатов
        - Рекомендации по принятию решения

        ### Как интерпретировать результаты:

        **✅ Статистически значимо (p-value < 0.05)**
        - Изменение не случайно
        - Можно принимать решение на основе результатов
        - Если улучшение - внедряйте изменение
        - Если ухудшение - откатывайте изменение

        **❌ Не значимо (p-value ≥ 0.05)**
        - Изменение может быть случайным
        - Недостаточно данных для выводов
        - Варианты:
          - Продлить эксперимент
          - Увеличить размер выборки
          - Оставить текущую версию

        ### Предупреждения:

        **⚠️ Малая выборка**
        - Менее 30 наблюдений на группу
        - Результаты могут быть ненадежными
        - Рекомендуется продлить эксперимент

        **⚠️ Эксперимент не завершен**
        - Данные не покрывают весь период
        - Показаны промежуточные результаты
        - Дождитесь окончания и обновите датасет

        💡 **Совет:** Всегда смотрите на p-value и размер выборки перед принятием решения.
        """)

    st.divider()

    # Дополнительные советы
    st.markdown("""
    ## 💡 Полезные советы

    ### Планирование эксперимента:
    - 📊 Определите ключевую метрику до начала эксперимента
    - 📈 Рассчитайте необходимый размер выборки
    - ⏰ Планируйте длительность минимум 1-2 недели
    - 🎯 Тестируйте одно изменение за раз

    ### Во время эксперимента:
    - 🚫 Не останавливайте эксперимент раньше времени
    - 📊 Не принимайте решения на основе промежуточных результатов
    - 🔍 Следите за аномалиями в данных
    - 📝 Документируйте все изменения

    ### После эксперимента:
    - ✅ Проверьте статистическую значимость
    - 📊 Посмотрите на дополнительные метрики
    - 🤔 Подумайте о долгосрочных эффектах
    - 📈 Внедряйте изменения постепенно

    ### Типичные ошибки:
    - ❌ Слишком короткий период эксперимента
    - ❌ Малый размер выборки
    - ❌ Множественное тестирование без корректировки
    - ❌ Остановка эксперимента при первых положительных результатах
    - ❌ Игнорирование статистической значимости
    """)

    st.divider()

    # Пример workflow
    st.markdown("""
    ## 🎯 Пример: Тестирование новой кнопки оформления заказа

    **Цель:** Увеличить конверсию в покупку

    **Шаг 1:** Загружаем датасет с данными о заказах (user_id, order_date, revenue, status)

    **Шаг 2:** Создаем метрику "Conversion Rate" с полем status и значением успеха "completed"

    **Шаг 3:** Создаем эксперимент:
    - Название: "Новая зеленая кнопка оформления"
    - Период: 01.03.2025 - 15.03.2025 (2 недели)
    - Группы: 50/50 (control/test)
    - Тест: z-test (для конверсии)

    **Шаг 4:** Проводим эксперимент 2 недели

    **Шаг 5:** Обновляем датасет с данными за весь период

    **Шаг 6:** Рассчитываем результаты:
    - Control: 12.5% конверсия (n=500)
    - Test: 14.8% конверсия (n=500)
    - Разница: +18.4%
    - p-value: 0.023 < 0.05 ✅
    - **Вывод:** Статистически значимое улучшение! Внедряем новую кнопку.
    """)

    st.divider()

    # Кнопка возврата
    if st.button("← Вернуться на главную", use_container_width=True):
        st.session_state.current_page = "Главная"
        st.rerun()
